import subprocess

cases = [
    # TC1: 후보 1개, 단순 체인
    ("3 2 1\n10 20 30\n1\n1 2 5\n2 3 5",
     "1번 보수(T=5): 각 구역 진압=[5,10,15], max=15"),

    # TC2: 후보 2개, 최선/최악 분리
    ("3 2 2\n10 100 30\n1 2\n1 2 5\n2 3 5",
     "1번 보수(T=5)→max=15, 2번 보수(T=50)→max=20"),

    # TC3: 대칭 사이클 그래프
    ("4 4 2\n20 10 10 20\n1 4\n1 2 1\n2 3 1\n3 4 1\n1 4 1",
     "대칭이라 어느 쪽 보수해도 동일"),

    # TC4: N=2 최소
    ("2 1 1\n100 100\n1\n1 2 10",
     "1번 보수(T=50): 진압=[50,60], max=60"),

    # TC5: 양끝 큰 값, 가운데 후보가 최선
    ("5 4 3\n50 10 10 10 50\n1 3 5\n1 2 1\n2 3 1\n3 4 1\n4 5 1",
     "3번 보수(T=5)→max=7(최선), 1 or 5번 보수→max=11(최악)"),

    # TC6: 모두 동일 T=10, 보수해도 병목 불변
    ("4 3 2\n10 10 10 10\n2 3\n1 2 5\n2 3 5\n3 4 5",
     "어느 쪽 보수해도 병목구역(양끝)은 진압시간 10 유지"),

    # TC7: 완전그래프 3개 노드
    ("3 3 2\n6 10 8\n1 3\n1 2 1\n2 3 1\n1 3 3",
     "1번 보수(T=3)→max=5, 3번 보수(T=4)→max=6"),
]

for i, (inp, desc) in enumerate(cases, 1):
    result = subprocess.run(
        ["python3", "a.py"],
        input=inp, capture_output=True, text=True
    ).stdout.strip()
    print(f"TC{i}: {result}  -- {desc}")
